import fs from 'node:fs';
import path from 'node:path';
import { resolveAgentPayHome } from '../../packages/config/src/index.js';
import {
  assertBootstrapSetupSummaryLeaseIsActive,
  cleanupBootstrapAgentCredentialsFile,
  readBootstrapAgentCredentialsFile,
  readBootstrapSetupSummaryFile,
} from './bootstrap-credentials.js';
import { assertTrustedDirectoryPath, assertTrustedPrivateFilePath } from './fs-trust.js';

const AUTO_GENERATED_BOOTSTRAP_FILE_PATTERN = /^bootstrap-\d+-\d+\.json$/u;
/**
 * Plaintext private-key files written by `agentpay admin setup --restore-wallet-from` while the
 * Rust bootstrap imports the wallet. They are removed after setup, but a crash or SIGKILL can
 * leave one behind, so they are scanned alongside auto-generated bootstrap files.
 */
export const TEMPORARY_WALLET_IMPORT_KEY_FILE_PATTERN = /^wallet-import-key-\d+-\d+\.key$/u;
const MAX_AUTO_GENERATED_BOOTSTRAP_FILES = 128;

export type BootstrapArtifactKind = 'bootstrap' | 'wallet-import-key';
export type BootstrapArtifactStatus = 'plaintext' | 'redacted' | 'invalid' | 'untrusted';

export interface BootstrapArtifactCheck {
  path: string;
  kind: BootstrapArtifactKind;
  status: BootstrapArtifactStatus;
  agentKeyId: string | null;
  leaseExpiresAt: string | null;
  leaseExpired: boolean;
  error: string | null;
}

export interface CleanupBootstrapArtifactResult extends BootstrapArtifactCheck {
  cleanup: 'deleted' | 'redacted' | 'skipped' | 'failed';
  skipReason?: string;
}

export interface CleanupBootstrapArtifactsResult {
  agentpayHome: string;
  action: 'deleted' | 'redacted';
  files: CleanupBootstrapArtifactResult[];
}

interface BootstrapArtifactsDeps {
  resolveAgentPayHome?: () => string;
  readdirSync?: typeof fs.readdirSync;
  /**
   * Returns a human-readable reason to keep an artifact untouched, or null to clean it up.
   * Used by `agentpay repair` so a bootstrap file is never deleted while it is still the only
   * copy of an agent auth token.
   */
  retainArtifact?: (artifact: BootstrapArtifactCheck) => string | null;
}

interface AutoGeneratedArtifactPath {
  path: string;
  kind: BootstrapArtifactKind;
}

function renderError(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function resolveArtifactKind(fileName: string): BootstrapArtifactKind | null {
  if (AUTO_GENERATED_BOOTSTRAP_FILE_PATTERN.test(fileName)) {
    return 'bootstrap';
  }
  if (TEMPORARY_WALLET_IMPORT_KEY_FILE_PATTERN.test(fileName)) {
    return 'wallet-import-key';
  }
  return null;
}

function resolveAutoGeneratedArtifactPaths(
  agentpayHome: string,
  deps: BootstrapArtifactsDeps = {},
): AutoGeneratedArtifactPath[] {
  const readdirSync = deps.readdirSync ?? fs.readdirSync;
  const resolvedHome = path.resolve(agentpayHome);
  try {
    assertTrustedDirectoryPath(resolvedHome, 'AgentPay home');
  } catch {
    return [];
  }

  let entries: fs.Dirent[];
  try {
    entries = readdirSync(resolvedHome, { withFileTypes: true }) as fs.Dirent[];
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
      return [];
    }
    throw error;
  }

  return entries
    .flatMap((entry) => {
      const kind = resolveArtifactKind(entry.name);
      return kind ? [{ path: path.join(resolvedHome, entry.name), kind }] : [];
    })
    .sort((left, right) => right.path.localeCompare(left.path))
    .slice(0, MAX_AUTO_GENERATED_BOOTSTRAP_FILES);
}

export function inspectTemporaryWalletImportKeyArtifact(
  targetPath: string,
): BootstrapArtifactCheck {
  const resolvedPath = path.resolve(targetPath);
  const base = {
    path: resolvedPath,
    kind: 'wallet-import-key' as const,
    agentKeyId: null,
    leaseExpiresAt: null,
    leaseExpired: false,
  };

  try {
    assertTrustedPrivateFilePath(resolvedPath, 'temporary wallet import key file');
  } catch (error) {
    return {
      ...base,
      status: 'untrusted',
      error: renderError(error),
    };
  }

  return {
    ...base,
    status: 'plaintext',
    error: null,
  };
}

export function inspectBootstrapArtifact(targetPath: string): BootstrapArtifactCheck {
  const resolvedPath = path.resolve(targetPath);
  const kind = 'bootstrap' as const;

  try {
    assertTrustedPrivateFilePath(resolvedPath, 'bootstrap file');
  } catch (error) {
    return {
      path: resolvedPath,
      kind,
      status: 'untrusted',
      agentKeyId: null,
      leaseExpiresAt: null,
      leaseExpired: false,
      error: renderError(error),
    };
  }

  let summary: ReturnType<typeof readBootstrapSetupSummaryFile>;
  try {
    summary = readBootstrapSetupSummaryFile(resolvedPath);
  } catch (error) {
    return {
      path: resolvedPath,
      kind,
      status: 'invalid',
      agentKeyId: null,
      leaseExpiresAt: null,
      leaseExpired: false,
      error: renderError(error),
    };
  }

  let leaseExpired = false;
  try {
    assertBootstrapSetupSummaryLeaseIsActive(summary);
  } catch (error) {
    const message = renderError(error);
    if (message.includes('lease has expired')) {
      leaseExpired = true;
    } else {
      return {
        path: resolvedPath,
        kind,
        status: 'invalid',
        agentKeyId: summary.agentKeyId,
        leaseExpiresAt: summary.leaseExpiresAt,
        leaseExpired: false,
        error: message,
      };
    }
  }

  try {
    const credentials = readBootstrapAgentCredentialsFile(resolvedPath);
    return {
      path: resolvedPath,
      kind,
      status: 'plaintext',
      agentKeyId: credentials.agentKeyId,
      leaseExpiresAt: summary.leaseExpiresAt,
      leaseExpired,
      error: null,
    };
  } catch (error) {
    const message = renderError(error);
    if (message.includes('contains a redacted agent auth token')) {
      if (summary.vaultPrivateKey !== null) {
        return {
          path: resolvedPath,
          kind,
          status: 'plaintext',
          agentKeyId: summary.agentKeyId,
          leaseExpiresAt: summary.leaseExpiresAt,
          leaseExpired,
          error: null,
        };
      }
      return {
        path: resolvedPath,
        kind,
        status: 'redacted',
        agentKeyId: summary.agentKeyId,
        leaseExpiresAt: summary.leaseExpiresAt,
        leaseExpired,
        error: null,
      };
    }

    return {
      path: resolvedPath,
      kind,
      status: 'invalid',
      agentKeyId: summary.agentKeyId,
      leaseExpiresAt: summary.leaseExpiresAt,
      leaseExpired,
      error: message,
    };
  }
}

function inspectAutoGeneratedArtifact(target: AutoGeneratedArtifactPath): BootstrapArtifactCheck {
  return target.kind === 'wallet-import-key'
    ? inspectTemporaryWalletImportKeyArtifact(target.path)
    : inspectBootstrapArtifact(target.path);
}

export function listAutoGeneratedBootstrapArtifacts(
  deps: BootstrapArtifactsDeps = {},
): BootstrapArtifactCheck[] {
  const agentpayHome = (deps.resolveAgentPayHome ?? resolveAgentPayHome)();
  return resolveAutoGeneratedArtifactPaths(agentpayHome, deps).map(inspectAutoGeneratedArtifact);
}

function cleanupTemporaryWalletImportKeyArtifact(
  artifact: BootstrapArtifactCheck,
): CleanupBootstrapArtifactResult {
  // A leftover import key has no redacted form; the only safe outcome is deleting it.
  try {
    fs.rmSync(artifact.path, { force: true });
    return {
      ...artifact,
      cleanup: 'deleted',
    };
  } catch (error) {
    return {
      ...artifact,
      cleanup: 'failed',
      error: renderError(error),
    };
  }
}

export function cleanupAutoGeneratedBootstrapArtifacts(
  action: 'deleted' | 'redacted' = 'deleted',
  deps: BootstrapArtifactsDeps = {},
): CleanupBootstrapArtifactsResult {
  const agentpayHome = path.resolve((deps.resolveAgentPayHome ?? resolveAgentPayHome)());
  assertTrustedDirectoryPath(agentpayHome, 'AgentPay home');

  const files = resolveAutoGeneratedArtifactPaths(agentpayHome, deps).map((target) => {
    const artifact = inspectAutoGeneratedArtifact(target);
    if (artifact.status !== 'plaintext' && artifact.status !== 'redacted') {
      return {
        ...artifact,
        cleanup: 'skipped' as const,
      };
    }

    const retainReason = deps.retainArtifact?.(artifact) ?? null;
    if (retainReason) {
      return {
        ...artifact,
        cleanup: 'skipped' as const,
        skipReason: retainReason,
      };
    }

    if (artifact.kind === 'wallet-import-key') {
      return cleanupTemporaryWalletImportKeyArtifact(artifact);
    }

    const result = cleanupBootstrapAgentCredentialsFile(target.path, action);
    if (result.action === 'failed') {
      return {
        ...artifact,
        path: result.sourcePath,
        cleanup: 'failed' as const,
        error: result.error,
      };
    }

    const cleanup = result.action === 'missing' ? ('skipped' as const) : result.action;

    return {
      ...artifact,
      path: result.sourcePath,
      cleanup,
    };
  });

  return {
    agentpayHome,
    action,
    files,
  };
}
