//! Generators for the machine-readable forms of this contract.
//!
//! `cargo xtask gen-api` writes their output to `docs/api/schema.json` and
//! `client/src/generated/`, and `cargo xtask gen-api --check` fails when the
//! checked-in files differ, so the published schema and the TypeScript client
//! types can never drift from these Rust types.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};

use schemars::generate::SchemaSettings;
use serde_json::{json, Value};
use ts_rs::{Config, ExportError, TypeVisitor, TS};

use crate::{
    DaemonRpcRequest, DaemonRpcResponse, HelloResponse, PaymentsRpcRequest, PaymentsRpcResponse,
    WireDaemonError, WirePaymentsError, WireRequest, WireResponse, API_VERSION,
    MAX_WIRE_BODY_BYTES,
};

/// Header placed at the top of every generated TypeScript file.
pub const GENERATED_TS_HEADER: &str =
    "// Generated by `cargo xtask gen-api` from crates/agentpay-api. Do not edit.\n";

/// Returns the JSON Schema (draft 2020-12) of every wire type, as one document
/// whose `$defs` hold the envelopes, requests, responses, and errors.
#[must_use]
pub fn json_schema() -> Value {
    let mut generator = SchemaSettings::draft2020_12().into_generator();
    let roots = [
        ("WireRequest", generator.subschema_for::<WireRequest>()),
        ("WireResponse", generator.subschema_for::<WireResponse>()),
        (
            "DaemonRpcRequest",
            generator.subschema_for::<DaemonRpcRequest>(),
        ),
        (
            "DaemonRpcResponse",
            generator.subschema_for::<DaemonRpcResponse>(),
        ),
        (
            "WireDaemonError",
            generator.subschema_for::<WireDaemonError>(),
        ),
        ("HelloResponse", generator.subschema_for::<HelloResponse>()),
        (
            "PaymentsRpcRequest",
            generator.subschema_for::<PaymentsRpcRequest>(),
        ),
        (
            "PaymentsRpcResponse",
            generator.subschema_for::<PaymentsRpcResponse>(),
        ),
        (
            "WirePaymentsError",
            generator.subschema_for::<WirePaymentsError>(),
        ),
    ];
    let roots: BTreeMap<&str, Value> = roots
        .into_iter()
        .map(|(name, schema)| (name, schema.to_value()))
        .collect();
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "AgentPay daemon API",
        "description": "Wire types of the AgentPay daemon API. A client sends one WireRequest frame whose body_json is a serialized DaemonRpcRequest (signer daemon) or PaymentsRpcRequest (payments service); the service answers with one WireResponse frame whose body_json is a DaemonRpcResponse / PaymentsRpcResponse (ok = true) or a WireDaemonError / WirePaymentsError (ok = false). See docs/daemon-api.md.",
        "x-api-version": API_VERSION,
        "x-max-wire-body-bytes": MAX_WIRE_BODY_BYTES,
        "x-roots": roots,
        "$defs": generator.take_definitions(true),
    })
}

/// Returns the TypeScript bindings as `file name -> contents`: one file per
/// wire type (with `import type` lines for its dependencies) plus `index.ts`,
/// which re-exports every type and defines the API constants.
pub fn typescript_bindings() -> Result<BTreeMap<String, String>, ExportError> {
    let config = Config::new().with_large_int("number");
    let mut collector = Collector {
        config: &config,
        seen: HashSet::new(),
        files: BTreeMap::new(),
        error: None,
    };
    collector.visit::<WireRequest>();
    collector.visit::<WireResponse>();
    collector.visit::<DaemonRpcRequest>();
    collector.visit::<DaemonRpcResponse>();
    collector.visit::<WireDaemonError>();
    collector.visit::<PaymentsRpcRequest>();
    collector.visit::<PaymentsRpcResponse>();
    collector.visit::<WirePaymentsError>();
    if let Some(error) = collector.error {
        return Err(error);
    }
    let mut files = collector.files;
    let index = index_ts(files.keys());
    files.insert("index.ts".to_string(), index);
    Ok(files)
}

/// Walks the dependency graph of the root types, rendering each exportable type once.
struct Collector<'a> {
    config: &'a Config,
    seen: HashSet<TypeId>,
    files: BTreeMap<String, String>,
    error: Option<ExportError>,
}

impl TypeVisitor for Collector<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if self.error.is_some() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        let Some(path) = T::output_path() else {
            return;
        };
        let file_name = path.to_string_lossy().into_owned();
        if !self.files.contains_key(&file_name) {
            match T::export_to_string(self.config) {
                Ok(contents) => {
                    self.files
                        .insert(file_name, with_generated_header(&contents));
                }
                Err(error) => {
                    self.error = Some(error);
                    return;
                }
            }
        }
        T::visit_dependencies(self);
        T::visit_generics(self);
    }
}

/// Replaces ts-rs' own banner with [`GENERATED_TS_HEADER`].
fn with_generated_header(contents: &str) -> String {
    let body = contents
        .strip_prefix("// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n")
        .unwrap_or(contents);
    format!("{GENERATED_TS_HEADER}{body}")
}

/// Renders `index.ts`: API constants plus a type re-export per generated file.
fn index_ts<'a>(file_names: impl Iterator<Item = &'a String>) -> String {
    let mut out = String::from(GENERATED_TS_HEADER);
    out.push('\n');
    out.push_str("/** Wire-contract version implemented by these types (semver). */\n");
    out.push_str(&format!(
        "export const API_VERSION = \"{API_VERSION}\";\n\n"
    ));
    out.push_str("/** Maximum frame payload size accepted by the daemon, in bytes. */\n");
    out.push_str(&format!(
        "export const MAX_WIRE_BODY_BYTES = {MAX_WIRE_BODY_BYTES};\n\n"
    ));
    out.push_str("/** Every signer daemon method name; each is also a `Hello` capability. */\n");
    out.push_str("export const METHOD_NAMES = [\n");
    for method in DaemonRpcRequest::METHOD_NAMES {
        out.push_str(&format!("  \"{method}\",\n"));
    }
    out.push_str("] as const;\n\n");
    out.push_str("/** Every payments service method name; each is also a `Hello` capability. */\n");
    out.push_str("export const PAYMENTS_METHOD_NAMES = [\n");
    for method in PaymentsRpcRequest::METHOD_NAMES {
        out.push_str(&format!("  \"{method}\",\n"));
    }
    out.push_str("] as const;\n\n");
    for file_name in file_names {
        let module = file_name.trim_end_matches(".ts");
        out.push_str(&format!(
            "export type {{ {module} }} from \"./{module}\";\n"
        ));
    }
    out
}
